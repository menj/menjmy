/**
 * Returns the social icon row HTML, or empty string if no platforms are set.
 * Called directly in footer.php.
 */
function book_wp_social_icons() {
    $platforms = book_wp_social_platforms();
    $items     = '';

    foreach ( $platforms as $slug => $meta ) {
        $url = get_option( 'book_wp_social_' . $slug, '' );

        // RSS fallback — use WordPress feed URL if field is blank
        if ( '' === $url && ! empty( $meta['rss'] ) ) {
            $url = get_feed_link();
        }

        if ( empty( $url ) ) continue;

        $icon  = book_wp_social_icon( $slug );
        $label = esc_html( $meta['label'] );
        $href  = esc_url( $url );

        $items .= '<li class="bwp-social__item">'
            . '<a class="bwp-social__link bwp-social__link--' . esc_attr( $slug ) . '"'
            . ' href="' . $href . '"'
            . ' target="_blank"'
            . ' rel="noopener noreferrer me"'
            . ' aria-label="' . $label . '">'
            . $icon
            . '<span class="screen-reader-text">' . $label . '</span>'
            . '</a>'
            . '</li>';
    }

    if ( '' === $items ) return '';

    return '<ul class="bwp-social" aria-label="' . esc_attr__( 'Social profiles', 'book-wp' ) . '">'
        . $items
        . '</ul>';
}
